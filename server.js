async function generateContentWithFallback(ai, prompt) {
  // مصفوفة تبدأ بأحدث النماذج المتاحة من جوجل مع نماذج احتياطية
  const modelsToTry = [
    'gemini-3.6-flash',
    'gemini-3.5-flash',
    'gemini-2.5-flash'
  ];

  let lastError = null;

  for (const modelName of modelsToTry) {
    try {
      const response = await ai.models.generateContent({
        model: modelName,
        contents: prompt,
        config: { responseMimeType: 'application/json' }
      });
      return response;
    } catch (err) {
      console.warn(`تعذر الاستجابة من النموذج ${modelName}: ${err.message}`);
      lastError = err;
    }
  }

  throw new Error(`جميع نماذج الفحص غير متاحة حالياً. التفاصيل: ${lastError?.message || 'خطأ في الاتصال'}`);
}

app.post('/api/analyze', upload.single('documentFile'), async (req, res) => {
  try {
    const { actionType, rawText } = req.body;
    let extractedText = rawText || '';

    // استخراج النص من ملفات Word أو PDF إذا تم رفع ملف
    if (req.file) {
      const fileName = req.file.originalname.toLowerCase();
      if (fileName.endsWith('.docx')) {
        const result = await mammoth.extractRawText({ buffer: req.file.buffer });
        extractedText = result.value;
      } else if (fileName.endsWith('.pdf')) {
        const pdfData = await pdfParse(req.file.buffer);
        extractedText = pdfData.text;
      }
    }

    if (!extractedText || !extractedText.trim()) {
      return res.status(400).json({ success: false, message: 'لم يتم العثور على نص لفحصه (يرجى إرفاق ملف Word/PDF أو لصق النص).' });
    }

    const rules = SERVICE_RULES[actionType || 'NewLawsuit'];
    if (!rules) {
      return res.status(400).json({ success: false, message: 'نوع الخدمة القضائية المحدد غير معروف.' });
    }

    const ai = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY });

    const prompt = `
أنت محرك فحص وتدقيق للعرائض والنماذج القضائية. مهمتك مراجعة المستند المرفق وتدقيقه سواء كان مكتوباً على شكل فقرات، أو قوائم، أو نص حر، بناءً على الشروط والملاحظات التالية:

${rules}

النص المراد تدقيقه:
"""
${extractedText}
"""

تعليمات صارمة للإخراج:
1. قم باستخلاص البيانات من النص الحر أو الفقرات، وتحقق من توفر جميع الحقول المطلوبة وضوابطها لكل الأطراف ولكل المرفقات المذكورة في النص.
2. تجاهل الحقول غير المطلوبة (مثل الجنسية، الجنس، العمر، المحافظة، التاريخ الهجري للمرفقات، والمبالغ المسددة اختيارياً).
3. استخدم العبارات والأسماء العربية الصريحة المفهومة للمستخدم العادي (مثال: "اسم المدعي الأول الرباعي", "اسم الوكيل للمدعى عليه الثاني", "تاريخ المرفق الأول", "عدد صفحات المرفق الثاني").
4. يمنع منعاً باتاً استخدام المصطلحات الإنجليزية أو أسماء الحقول البرمجية مثل (Plaintiffs, Defendants, LitName, LawsEDate, NatiNo, LitEmail, AttName).
5. اذكر فقط البيانات الناقصة أو غير المتطابقة مع القيود المحددة.

نسّق النتيجة كـ JSON كالتالي حصراً:
{
  "isReadyForSubmission": true / false,
  "missingFields": [
    "اسم الحقل أو الطرف أو المرفق الناقص باللغة العربية الواضحة"
  ],
  "validationErrors": [
    {"fieldName": "اسم الحقل أو المرفق بالعربي المفهوم", "issueDescription": "شرح الخطأ أو التعارض بأسلوب عربي بسيط مع تحديد الشخص أو المرفق"}
  ]
}`;

    const response = await generateContentWithFallback(ai, prompt);
    const analysisResult = JSON.parse(response.text);
    return res.json(analysisResult);

  } catch (error) {
    console.error('خطأ في السيرفر:', error);
    return res.status(500).json({ success: false, message: error.message || 'حدث خطأ في السيرفر أثناء تدقيق المستند.' });
  }
});

